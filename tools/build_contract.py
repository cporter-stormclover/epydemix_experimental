"""Build AGENT.md, the agent contract, from its hand-written core and the code.

    python tools/build_contract.py            # write AGENT.md and epydemix/_contract.py
    python tools/build_contract.py --check    # fail if either is out of date

``docs/agent/core.md`` holds the hand-written parts (workflow, principles,
translation guide, failure modes, worked examples). Three placeholders in it
are filled from the code, so they cannot drift from it:

* ``<!-- contract:cli-reference -->``: every command, its arguments and
  options, from the click command tree;
* ``<!-- contract:config-schema -->``: the parameters of the predefined
  models and modules (from their registries' JSON Schema), the config keys
  by schema version, and the semantic checks;
* ``<!-- contract:output-shapes -->``: the JSON each command prints, from the
  dataclasses in ``epydemix/cli/responses.py``.

The contract must stay under a token ceiling. Tokens are estimated as
characters / 4 (no tokenizer dependency, so the count is the same everywhere).
``epydemix/_contract.py`` records the contract's hash, which every bundle's
provenance carries as ``contract_version``.
"""

import argparse
import hashlib
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

CORE = ROOT / "docs" / "agent" / "core.md"
AGENT_MD = ROOT / "AGENT.md"
CONTRACT_PY = ROOT / "epydemix" / "_contract.py"
TOKEN_CEILING = 12_000

HEADER = (
    "<!-- Generated by tools/build_contract.py from docs/agent/core.md and the "
    "code. Do not edit this file: edit the sources and run the tool. -->\n\n"
)

COMMAND_ORDER = [
    "models",
    "schema",
    "defaults",
    "populations",
    "validate",
    "derive",
    "run",
    "sweep",
    "calibrate",
    "project",
    "inspect",
    "compare",
    "verify",
    "replay",
]


def count_tokens(text: str) -> int:
    """Estimated tokens: characters / 4."""
    return math.ceil(len(text) / 4)


def _first_paragraph(text: str) -> str:
    paragraph = (text or "").strip().split("\n\n")[0]
    return " ".join(paragraph.split())


def render_cli_reference() -> str:
    import click

    from epydemix.cli.main import cli

    commands = cli.commands
    names = [n for n in COMMAND_ORDER if n in commands] + sorted(
        n for n in commands if n not in COMMAND_ORDER
    )
    lines = ["## CLI reference", ""]
    lines.append(
        "Generated from the command tree; `epydemix COMMAND --help` prints the "
        "full help with examples."
    )
    lines.append("")
    for name in names:
        cmd = commands[name]
        args = []
        for p in cmd.params:
            if isinstance(p, click.Argument):
                metavar = p.name.upper()
                if p.nargs == -1:
                    metavar += "..."
                args.append(metavar if p.required else f"[{metavar}]")
        lines.append(
            f"- **`epydemix {' '.join([name] + args)}`** — {_first_paragraph(cmd.help)}"
        )
        for p in cmd.params:
            if not isinstance(p, click.Option) or p.hidden:
                continue
            flag = ", ".join(f"`{o}`" for o in sorted(p.opts, key=len))
            details = []
            if isinstance(p.type, click.Choice):
                details.append("|".join(p.type.choices))
            if not p.is_flag and p.default not in (None, False, ()):
                details.append(f"default {p.default}")
            extra = f" ({'; '.join(details)})" if details else ""
            lines.append(f"  - {flag}{extra}: {_first_paragraph(p.help)}")
    return "\n".join(lines)


def _all_parameter_specs():
    """Every parameter of the predefined models and modules, with its users."""
    from epydemix.model.predefined_models import SUPPORTED_MODELS, load_predefined_model

    variants = [(m, {}) for m in SUPPORTED_MODELS] + [
        ("SIR", {"waning_immunity": True}),
        ("SIR", {"vaccination": True}),
        ("SIR", {"outcome": "deaths"}),
        ("SIR", {"outcome": "hospitalization"}),
    ]
    labels = {
        "waning_immunity": "waning_immunity",
        "vaccination": "vaccination",
        "outcome": None,
    }
    specs, users, checks = {}, {}, []
    for model_name, modules in variants:
        model = load_predefined_model(model_name, **modules)
        schema = model.parameter_registry.to_json_schema()
        checks = schema.get("x-semantic-checks", checks)
        base = set(load_predefined_model(model_name).parameter_registry.names)
        for name, prop in schema["properties"].items():
            if modules and name in base:
                continue
            specs.setdefault(name, prop)
            if modules:
                key, value = next(iter(modules.items()))
                user = f"outcome: {value}" if labels[key] is None else key
            else:
                user = model_name
            users.setdefault(name, [])
            if user not in users[name]:
                users[name].append(user)
    return specs, users, checks


def render_config_schema() -> str:
    from epydemix.cli.schema_version import CONFIG_SCHEMA_VERSION, INTRODUCED

    specs, users, checks = _all_parameter_specs()
    lines = ["## Config schema", ""]
    lines.append(
        f"Config `schema_version` {CONFIG_SCHEMA_VERSION}. Keys added by each "
        "version (older configs stay valid):"
    )
    lines.append("")
    for version, keys in INTRODUCED.items():
        listed = ", ".join(f"`{k}`" for k in keys) or "the original grammar"
        lines.append(f"- {version}: {listed}")
    lines.append("")
    lines.append(
        "Parameters of the predefined models and modules (`epydemix schema MODEL` "
        "has descriptions and band sources):"
    )
    lines.append("")
    lines.append("| Parameter | Used by | Default | Range | Units | Sig. figs |")
    lines.append("|---|---|---|---|---|---|")
    for name, prop in specs.items():
        units = re.search(r"Units: ([^.]+)\.", prop.get("description", ""))
        rng = f"{prop.get('minimum', '')}–{prop.get('maximum', '')}"
        default = prop.get("default")
        if isinstance(default, float):
            default = f"{default:.4g}"
        lines.append(
            f"| `{name}` | {', '.join(users[name])} | {default} | {rng} | "
            f"{units.group(1) if units else ''} | {prop.get('x-precision', '')} |"
        )
        bands = prop.get("x-qualitative-bands")
        if bands:
            text = ", ".join(f"{b} {v['min']}–{v['max']}" for b, v in bands.items())
            lines.append(f"| ↳ bands | {text} | | | | |")
    lines.append("")
    lines.append("Semantic checks (`x-semantic-checks`):")
    lines.append("")
    for check in checks:
        target = check.get("parameter") or check.get("section") or check.get("quantity")
        lines.append(
            f"- `{check['name']}` ({check['severity']}, {target}): {check['message']}"
        )
    return "\n".join(lines)


def render_output_shapes() -> str:
    from epydemix.cli.responses import RESPONSES, render

    lines = ["## Output shapes", ""]
    lines.append(
        "What each command prints (`?` marks keys that may be absent). Generated "
        "from `epydemix/cli/responses.py`, which the tests check the commands against."
    )
    lines.append("")
    for model in RESPONSES:
        doc = " ".join((model.__doc__ or "").split())
        shape = render(model)
        lines.append(f"- {doc} `{shape}`" if shape else f"- {doc}")
    return "\n".join(lines)


SECTIONS = {
    "<!-- contract:cli-reference -->": render_cli_reference,
    "<!-- contract:config-schema -->": render_config_schema,
    "<!-- contract:output-shapes -->": render_output_shapes,
}


def assemble(core: str) -> str:
    text = core
    for marker, render in SECTIONS.items():
        if marker not in text:
            raise SystemExit(f"{CORE} has no {marker} placeholder")
        text = text.replace(marker, render())
    return HEADER + text.strip() + "\n"


def contract_module(text: str) -> str:
    digest = hashlib.sha256(text.encode()).hexdigest()
    return (
        '"""Version of the agent contract (AGENT.md) this epydemix ships with.\n\n'
        "Generated by tools/build_contract.py. Do not edit.\n"
        '"""\n\n'
        # Wrapped as ruff formats it (the line would exceed 88 characters).
        f'CONTRACT_VERSION = (\n    "sha256:{digest}"\n)\n'
        f"CONTRACT_TOKENS = {count_tokens(text)}\n"
    )


def build():
    text = assemble(CORE.read_text())
    tokens = count_tokens(text)
    if tokens >= TOKEN_CEILING:
        raise SystemExit(
            f"AGENT.md is {tokens} tokens, over the ceiling of {TOKEN_CEILING}"
        )
    return text, contract_module(text), tokens


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if AGENT.md or epydemix/_contract.py is out of date.",
    )
    args = parser.parse_args(argv)
    text, module, tokens = build()
    if args.check:
        stale = [
            p.relative_to(ROOT).as_posix()
            for p, content in ((AGENT_MD, text), (CONTRACT_PY, module))
            if not p.exists() or p.read_text() != content
        ]
        if stale:
            print(
                f"Out of date: {', '.join(stale)}. Run python tools/build_contract.py",
                file=sys.stderr,
            )
            return 1
        print(f"AGENT.md is up to date ({tokens} tokens, ceiling {TOKEN_CEILING})")
        return 0
    AGENT_MD.write_text(text)
    CONTRACT_PY.write_text(module)
    print(f"Wrote AGENT.md ({tokens} tokens, ceiling {TOKEN_CEILING})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
